"""A DaVinci Resolve script that opens an exported timeline and marks matchcut's junctions.

``resolve_script`` returns the text of a Python script for the user to run themselves; matchcut never runs it and never imports
``DaVinciResolveScript``.  It uses only scripting calls documented in the Resolve 21.0.4 README (``scriptapp``, ``GetProjectManager``,
``GetCurrentProject``, ``GetMediaPool``, ``ImportTimelineFromFile``, ``SetCurrentTimeline``, ``OpenPage``, ``Timeline.AddMarker`` with the
junction id as customData (``Timeline.UpdateMarkerCustomData`` when a marker is already on the frame), ``SetCurrentTimecode``, ``GetTimelineCount``, ``GetTimelineByIndex``, ``GetName``).  It needs Resolve Studio
running with Preferences > System > General > External scripting using = Local.

What it cannot know is written into the script and into ``docs/INTEROP.md``: the start timecode of the imported timeline (every matchcut
exporter starts its record side at 00:00:00:00, which is what ``start_tc`` defaults to) and whether Resolve conforms timecoded camera
media from the source timecode the files carry.  Nothing here has been run against a real Resolve.
"""
from __future__ import annotations

import re
from fractions import Fraction
from typing import Dict, Mapping, Optional, Tuple

from . import InterchangeError
from .common import parse_timecode
from .edl import _tc as _timecode_text  # the one timecode formatter (non-drop, or drop-frame for 29.97 / 59.94)

_TEMPLATE = '''#!/usr/bin/env python3
"""GENERATED by matchcut (python -m matchcut.pipeline.cli export --resolve-script). matchcut never runs this file: you do.

Opens the exported OTIO timeline in the open Resolve project and adds one marker per matchcut junction (customData = junction id).
Uses only scripting calls listed in the Resolve 21.0.4 README: scriptapp, GetProjectManager, GetCurrentProject, GetMediaPool,
ImportTimelineFromFile, SetCurrentTimeline, OpenPage, Timeline.AddMarker, Timeline.UpdateMarkerCustomData, Timeline.SetCurrentTimecode,
GetTimelineCount, GetTimelineByIndex, GetName. No transitions, fades or metadata are written by this script.

Needs DaVinci Resolve Studio running, with Preferences > System > General > External scripting using = Local.
Not run against a live Resolve by matchcut's authors (human gate, see docs/M2A-ACCEPTANCE.md). Assumptions this script cannot check, all UNVERIFIED:
  * start timecode: matchcut writes the record side of every export from 00:00:00:00 (START_TC below). It is assumed that the
    imported timeline starts there, so that marker frame ids are record frames counted from the timeline start and the playhead
    timecode is START_TC + the junction's record frame. Resolve's own default start timecode is often 01:00:00:00: if the
    markers or the playhead land elsewhere, set the timeline's start timecode to START_TC (Timeline Settings) or edit START_TC and NAVIGATE_TC.
  * media conform: the files carry source times in the media's embedded start timecode. It is assumed that Resolve relinks the
    camera media by path and conforms it from that timecode.
  * AddMarker returns False when a marker already sits on that frame (Resolve may bring matchcut's own OTIO markers along). The script
    then sets the junction id on that marker with Timeline.UpdateMarkerCustomData; a junction whose marker ends up without the id is
    counted and the script exits non-zero. Every other call's return value is checked too.
"""
import os
import sys

TIMELINE_FILE = @FILE@
TIMELINE_NAME = @NAME@
START_TC = @START@        # the start timecode matchcut wrote for the timeline (unverified in Resolve)
JUNCTIONS = @JUNCTIONS@   # junction id -> record frame of the cut point (frames from the timeline start)
NOTES = @NOTES@           # junction id -> (marker name, note)
NAVIGATE_TO = @NAV@
NAVIGATE_TC = @TC@


def load_api():
    try:
        import DaVinciResolveScript as dvr
    except ImportError:
        api = os.environ.get("RESOLVE_SCRIPT_API") or {
            "darwin": "/Library/Application Support/Blackmagic Design/DaVinci Resolve/Developer/Scripting",
            "win32": os.path.expandvars(r"%PROGRAMDATA%\\Blackmagic Design\\DaVinci Resolve\\Support\\Developer\\Scripting"),
        }.get(sys.platform, "/opt/resolve/Developer/Scripting")
        sys.path.append(os.path.join(api, "Modules"))
        import DaVinciResolveScript as dvr
    return dvr


def main():
    resolve = load_api().scriptapp("Resolve")
    if resolve is None:
        sys.exit("cannot reach Resolve (is it running, Studio, external scripting = Local?)")
    project = resolve.GetProjectManager().GetCurrentProject()
    if project is None:
        sys.exit("no project is open in Resolve")
    pool = project.GetMediaPool()
    timeline = pool.ImportTimelineFromFile(TIMELINE_FILE, {"timelineName": TIMELINE_NAME, "importSourceClips": True})
    if not timeline:  # the import failed or returned nothing: look for a timeline of that name
        for i in range(1, project.GetTimelineCount() + 1):
            if project.GetTimelineByIndex(i).GetName() == TIMELINE_NAME:
                timeline = project.GetTimelineByIndex(i)
        if timeline:
            print("timeline %s already existed: markers added to it; delete it and re-run to import the new export" % TIMELINE_NAME)
    if not timeline:
        sys.exit("timeline import failed: " + TIMELINE_FILE)
    if not project.SetCurrentTimeline(timeline):
        sys.exit("cannot make the timeline %s current" % TIMELINE_NAME)
    if not resolve.OpenPage("edit"):
        print("warning: could not open the Edit page")
    missing = []
    for jid, frame in JUNCTIONS.items():
        name, note = NOTES.get(jid, (jid, ""))
        if timeline.AddMarker(frame, "Green", name, note, 1, jid):  # customData = junction id
            continue
        # AddMarker is False when a marker already sits on that frame (Resolve may bring matchcut's own OTIO markers along):
        # give that marker the junction id instead
        if not timeline.UpdateMarkerCustomData(frame, jid):
            missing.append(jid)
    print("%d of %d junctions carry their id as marker customData" % (len(JUNCTIONS) - len(missing), len(JUNCTIONS))
          + ("; without it: " + ", ".join(missing) if missing else ""))
    problems = ["%d junctions have no marker with their id" % len(missing)] if missing else []
    if timeline.SetCurrentTimecode(NAVIGATE_TC):
        print("playhead at %s (%s)" % (NAVIGATE_TC, ("junction " + NAVIGATE_TO) if NAVIGATE_TO else "start of the timeline"))
    else:
        print("could not set the playhead to %s: the imported timeline may not start at %s: set START_TC" % (NAVIGATE_TC, START_TC))
        problems.append("playhead not set")
    if problems:
        sys.exit("; ".join(problems))


if __name__ == "__main__":
    main()
'''


def resolve_script(timeline_file: str, timeline_name: str, junction_frames: Mapping[str, int], navigate_to: str,
                   start_tc: str = "00:00:00:00", rate: Fraction = Fraction(24), notes: Optional[Mapping[str, Tuple[str, str]]] = None) -> str:
    """The text of a Resolve (Studio) Python script: import ``timeline_file`` as ``timeline_name``, add a marker per junction, park the playhead.

    ``junction_frames`` maps junction id -> record frame of its cut (from the timeline start); ``navigate_to`` is the id the playhead
    goes to (``""``: the start).  ``start_tc`` is the timeline's start timecode as matchcut wrote it (every exporter: 00:00:00:00); the
    playhead timecode is ``start_tc`` plus that junction's frame, at ``rate``.  ``notes`` maps junction id -> (marker name, note).
    """
    if not timeline_file:
        raise InterchangeError("no timeline file to import")
    if not timeline_name:
        raise InterchangeError("no timeline name")
    rate = Fraction(rate)
    start = parse_timecode(start_tc, rate)
    if start is None:
        raise InterchangeError(f"invalid start timecode {start_tc}: use HH:MM:SS:FF")
    for jid, frame in junction_frames.items():
        if not isinstance(frame, int) or frame < 0:
            raise InterchangeError(f"junction {jid} sits at record frame {frame}")
    if navigate_to and navigate_to not in junction_frames:
        have = ", ".join(junction_frames) if junction_frames else ""
        raise InterchangeError(f"cannot park the playhead at junction {navigate_to}: the cut has " + (f"junctions {have}" if have else "no junctions"))
    frames, drop = start
    tc = _timecode_text(frames + (junction_frames[navigate_to] if navigate_to else 0), rate, drop)
    subs = {"@FILE@": str(timeline_file), "@NAME@": str(timeline_name), "@START@": start_tc.strip(), "@JUNCTIONS@": dict(junction_frames),
            "@NOTES@": {k: tuple(v) for k, v in (notes or {}).items() if k in junction_frames}, "@NAV@": navigate_to, "@TC@": tc}
    return re.sub(r"@[A-Z]+@", lambda m: repr(subs[m.group(0)]) if m.group(0) in subs else m.group(0), _TEMPLATE)  # one pass: a value is never re-expanded
