"""The probe bundle: the stage exported for Resolve, what it should come back as, and the script that asks Resolve.

``build_bundle`` exports one stage with M2a's ``export_workspace`` (OTIO, FCPXML 1.10, EDL) into the bundle directory (default
``<ws>/resolve_probe``), writes ``expected.json`` (the canonical clips in frames, the junctions with their ids and record frames, the
rate and start timecode, the files and their sha256) and ``resolve_probe.py`` from the template ``_probe_script.py`` with the same data
written into it.  The script never imports matchcut; ``run_script`` runs it (``--run``) only after it has found Resolve's module.
"""
from __future__ import annotations

import hashlib
import json
import pprint
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from matchcut.interchange import MATCHCUT_VERSION, InterchangeError
from matchcut.interchange.common import export_timeline, junction_ids, layout, record_frames, truncate
from matchcut.interchange.fidelity import FORMATS
from matchcut.interchange.workspace import HUMAN, _bounds, _canonical, _source, export_workspace
from matchcut.pipeline.config import PipelineConfig
from matchcut.pipeline.junctions import build_junctions, scorer_for_workspace, stage_timeline_paths

from . import ProbeError

BUNDLE_DIR = "resolve_probe"
SCRIPT = "resolve_probe.py"
EXPECTED = "expected.json"
RESULT = "resolve_probe.json"
RUNS = "runs"  # every run of the script writes runs/<UTC time>/resolve_probe.json and runs/<UTC time>/exports/
REPORT = "probe_report.md"
EXPECTED_SCHEMA = "matchcut.resolve_probe_expected/1"
START_TC = "00:00:00:00"  # the record start every M2a exporter writes
TEMPLATE = Path(__file__).with_name("_probe_script.py")
_FILL = re.compile(r"^EXPECTED = None  # @EXPECTED@.*$", re.M)


@dataclass
class Bundle:
    dir: Path
    script: Path
    expected: Path
    files: List[Path] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)


def _sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def expected_doc(ws: Path, cfg: PipelineConfig, stage: str, out: Path) -> Dict[str, Any]:
    """What the probe should find in Resolve: the stage on the frame grid exactly as the bundle's files carry it."""
    canonical = _canonical(ws)
    by_stage = dict(canonical)
    src, _ = _source(ws, cfg)
    snapped, _ = export_timeline(by_stage[stage], _bounds(ws), src)
    rows = layout(snapped, src.rate)
    ids = junction_ids(snapped)
    junctions = build_junctions(canonical, scorer_for_workspace(ws, cfg), upto=stage)
    files = {"otio": f"{stage}.otio", "fcpxml": "matchcut.fcpxml", "edl": f"{stage}.edl"}
    clips = [{"index": r.index, "clip_id": c.id, "shot": c.shot_index, "in": r.in_f, "out": r.out_f, "vis_in": r.vis_in, "vis_out": r.vis_out,
              "rec_in": r.rec_in, "rec_out": r.rec_out, "dur": r.dur, "transition_in": {"kind": r.kind, "frames": r.tr, "head": r.head}}
             for c, r in zip(snapped.clips, rows)]
    js = []
    for j in junctions:
        if j.index + 1 >= len(rows):
            continue
        r = rows[j.index + 1]
        js.append({"id": ids[j.index], "index": j.index, "record_frame": r.cut, "kind": r.kind, "frames": r.tr, "head": r.head,
                   "name": f"J{j.index + 1} s{j.out_shot}->s{j.in_shot}", "note": truncate(j.why())})
    stage_path = dict(stage_timeline_paths(ws))[stage]
    return {
        "schema": EXPECTED_SCHEMA, "stage": stage, "matchcut_version": MATCHCUT_VERSION, "stage_sha256": _sha256(stage_path),
        "rate": [src.rate.numerator, src.rate.denominator], "start_tc": START_TC, "record_frames": record_frames(rows),
        "source": {"path": src.path, "url": src.url, "duration_frames": src.duration_frames, "start_tc_frames": src.start_tc_frames,
                   "start_tc_drop": src.start_tc_drop, "has_audio": src.has_audio, "width": src.width, "height": src.height},
        "files": files, "sha256": {k: _sha256(out / v) for k, v in sorted(files.items())},
        "clips": clips, "junctions": js,
    }


def script_text(expected: Dict[str, Any]) -> str:
    """``resolve_probe.py``: the template with ``expected`` written into it as a Python literal."""
    template = TEMPLATE.read_text(encoding="utf-8")
    literal = pprint.pformat(expected, width=140, sort_dicts=False)
    text, n = _FILL.subn(lambda m: "EXPECTED = " + literal, template, count=1)
    if n != 1:
        raise ProbeError(f"the probe template {TEMPLATE.name} has no EXPECTED line to fill")
    return text.replace("(GENERATED by `python -m matchcut.resolve probe`)", f"(GENERATED by `python -m matchcut.resolve probe`, matchcut {MATCHCUT_VERSION}, stage {expected['stage']})", 1)


def build_bundle(ws: Path, cfg: PipelineConfig, stage: str = "final", out: Optional[Path] = None) -> Bundle:
    """Export ``stage`` into the bundle and write ``expected.json`` and ``resolve_probe.py``.  A one-line ``ProbeError`` on any failure."""
    ws = Path(ws)
    out = Path(out) if out else ws / BUNDLE_DIR
    if stage == HUMAN:
        raise ProbeError("the human stage is an import result, not a canonical stage: probe one of the canonical stages")
    try:
        res = export_workspace(ws, cfg, (stage,), FORMATS, out)
        expected = expected_doc(ws, cfg, stage, out)
    except InterchangeError as exc:
        raise ProbeError(str(exc)) from exc
    except OSError as exc:
        raise ProbeError(f"cannot write the bundle in {out}: {exc.strerror or exc}") from exc
    exp_path, script = out / EXPECTED, out / SCRIPT
    exp_path.write_text(json.dumps(expected, indent=1) + "\n", encoding="utf-8")
    script.write_text(script_text(expected), encoding="utf-8")
    files = [out / v for v in expected["files"].values()] + [exp_path, script]
    notes = list(res.notes)
    if not expected["junctions"]:
        notes.append(f"stage {stage} has one clip: no junction to mark or navigate to")
    if not any(j["frames"] for j in expected["junctions"]):
        notes.append(f"stage {stage} has no dissolves: the probe cannot measure what Resolve does with them")
    return Bundle(out, script, exp_path, files, notes)


def command(script: Path, platform: Optional[str] = None) -> str:
    """The one command to run, quoted for the shell of this platform (the bundle is made on the machine that runs Resolve):
    ``py -3`` (the Python launcher) on Windows, ``python3`` elsewhere."""
    plat = platform or sys.platform
    return f'py -3 "{script}"' if plat.startswith("win") else f'python3 "{script}"'


def console_lines(script: Path) -> Tuple[str, str]:
    """(dry run, real run): the lines to paste into Resolve's own console (Workspace > Console, Py3), where ``resolve`` is Resolve's app
    object. Each runs the script with an explicit globals dict whose ``__file__`` is the script, so the bundle and the runs/ folder
    resolve; it does not touch ``sys.argv`` (runpy would, and the console may have none). ``console`` returns the exit code instead of
    raising SystemExit into Resolve and never asks a question, so the real run passes --yes."""
    def line(args: List[str]) -> str:
        return (f'_mc_p = {str(script)!r}; _mc_g = {{"__file__": _mc_p, "__name__": "resolve_probe_console"}}; '
                f'exec(compile(open(_mc_p, encoding="utf-8").read(), _mc_p, "exec"), _mc_g); '
                f'print("matchcut probe exit", _mc_g["console"](resolve, {args!r}))')
    return line(["--dry-run"]), line(["--yes"])


def run_script(script: Path, extra: Optional[List[str]] = None, python: str = sys.executable) -> int:
    """``--run``: run the script here when Resolve's scripting module can be imported (asked of the script itself), else say so plainly."""
    check = subprocess.run([python, str(script), "--check-module"], capture_output=True, text=True)
    if check.returncode != 0:
        print("Resolve's scripting module (DaVinciResolveScript) cannot be imported on this machine, so the probe was not run. "
              "Run it where Resolve Studio is installed and open, with the command above (it prints what to set if it cannot find the module).")
        return 2
    return subprocess.run([python, str(script)] + list(extra or [])).returncode
